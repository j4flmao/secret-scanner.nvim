local M = {}

local config = require("secret-scanner.config")

--- Marker written into every hook we manage, used to detect ownership.
local MARKER = "# MANAGED BY secret-scanner.nvim -- do not edit"

--- Locate the hooks directory for a repo.
--- @param repo_root string
--- @return string|nil dir
--- @return string|nil error
local function hooks_dir(repo_root)
  local result = vim.system({ "git", "rev-parse", "--absolute-git-dir" }, { text = true, cwd = repo_root }):wait()
  if result.code ~= 0 then
    local stderr = (result.stderr or ""):gsub("%s+$", "")
    local detail = stderr ~= "" and stderr or "git rev-parse failed"
    return nil, "not a git repository: " .. detail
  end
  local gitdir = (result.stdout or ""):gsub("%s+$", "")
  local dir = gitdir .. "/hooks"
  vim.fn.mkdir(dir, "p")
  return dir
end

--- @param hook_name string
--- @return string
local function backup_name(hook_name)
  return hook_name .. "~legacy"
end

--- Copy a file with plain Lua (vim.fn.copyfile is not available).
--- @param src string
--- @param dst string
local function copy_file(src, dst)
  local f, err = io.open(src, "rb")
  if not f then
    return false, err
  end
  local content = f:read("*a")
  f:close()
  local out, werr = io.open(dst, "wb")
  if not out then
    return false, werr
  end
  out:write(content)
  out:close()
  return true
end

--- Build the standalone shell script for a hook. Deliberately self-contained:
--- no dependency on Neovim being open at commit time.
--- @param hook_name string "pre-commit" | "pre-push"
--- @return string[]
local function build_script(hook_name)
  local cfg = config.get()

  local resolved = vim.fn.exepath(cfg.gitleaks_path)
  local gitleaks = resolved ~= "" and resolved or cfg.gitleaks_path

  local mode = cfg.block_commit_on_finding and "block" or "warn"

  local extra_args = ""
  if hook_name == "pre-commit" then
    extra_args = " --staged"
  end

  local config_lines = {}
  local config_args = ""
  if cfg.custom_config_path then
    local gitleaks_mod = require("secret-scanner.engine.gitleaks")
    local primary, err = gitleaks_mod.effective_config_path()
    if err then
      vim.notify("[secret-scanner] " .. err, vim.log.levels.WARN)
    end
    local original = cfg.custom_config_path
    local chosen = primary or original
    if chosen ~= original then
      -- Prefer the derived extend-config; if the cache was cleared since
      -- install, fall back to the original file (purely additive rules).
      table.insert(config_lines, string.format('CONFIG="%s"', chosen))
      table.insert(config_lines, string.format('if [ ! -r "$CONFIG" ] && [ -r "%s" ]; then', original))
      table.insert(config_lines, string.format('  CONFIG="%s"', original))
      table.insert(config_lines, "fi")
      config_args = ' --config "$CONFIG"'
    else
      config_args = ' --config "' .. original .. '"'
    end
  end

  local action = "staged changes"
  if hook_name == "pre-push" then
    action = "the commits being pushed"
  end

  local lines = {
    "#!/bin/sh",
    MARKER,
    "# Generated by :SecretScannerInstallHooks; remove with :SecretScannerUninstallHooks.",
    "# Runs any previous hook first, then the gitleaks check.",
    "",
    'HOOK="$0"',
    'DIR="$(CDPATH= cd -- "$(dirname -- "$HOOK")" && pwd)"',
    string.format('LEGACY="$DIR/%s"', backup_name(hook_name)),
    "",
    "# Chain a pre-existing hook, if one was backed up.",
    'if [ -x "$LEGACY" ]; then',
    '  "$LEGACY" "$@"',
    "  legacy_status=$?",
    '  if [ "$legacy_status" -ne 0 ]; then',
    '    exit "$legacy_status"',
    "  fi",
    "fi",
    "",
    string.format('GITLEAKS="%s"', gitleaks),
  }

  for _, line in ipairs(config_lines) do
    table.insert(lines, line)
  end

  if mode == "block" then
    table.insert(lines, 'if [ ! -x "$GITLEAKS" ]; then')
    table.insert(lines, '  echo "secret-scanner: gitleaks binary not found at: $GITLEAKS" >&2')
    table.insert(
      lines,
      '  echo "secret-scanner: install it from https://github.com/gitleaks/gitleaks#installation" >&2'
    )
    table.insert(lines, '  echo "secret-scanner: blocking commit because the security check could not run." >&2')
    table.insert(lines, "  exit 1")
    table.insert(lines, "fi")
    table.insert(lines, "")
  else
    table.insert(lines, 'if [ ! -x "$GITLEAKS" ]; then')
    table.insert(lines, '  echo "secret-scanner: gitleaks binary not found at: $GITLEAKS" >&2')
    table.insert(
      lines,
      '  echo "secret-scanner: install it from https://github.com/gitleaks/gitleaks#installation" >&2'
    )
    table.insert(lines, "  exit 0")
    table.insert(lines, "fi")
    table.insert(lines, "")
  end

  local tail = {
    string.format('"$GITLEAKS" git --%s%s%s', hook_name, extra_args, config_args),
    "status=$?",
    "",
    'if [ "$status" -eq 0 ]; then',
    "  exit 0",
    "fi",
    "",
    'echo "secret-scanner: gitleaks detected a potential secret in ' .. action .. '." >&2',
  }

  if mode == "block" then
    table.insert(tail, '  echo "  To allowlist a false positive, add the finding to .secretscannerignore." >&2')
    table.insert(tail, '  echo "  To override this check: git commit --no-verify" >&2')
    table.insert(tail, '  exit "$status"')
  end
  table.insert(tail, "exit 0")

  for _, line in ipairs(tail) do
    table.insert(lines, line)
  end
  return lines
end

--- Get the hooks directory for a repo.
--- @param repo_root? string
--- @return string|nil
--- @return string|nil error
function M.hooks_dir(repo_root)
  return hooks_dir(repo_root or vim.fn.getcwd())
end

--- Install hooks for the repo. Backs up (never destroys) existing hooks and
--- chains them.
--- @param repo_root? string
--- @return boolean success
function M.install(repo_root)
  local root = repo_root or vim.fn.getcwd()
  local dir, err = hooks_dir(root)
  if not dir then
    vim.notify("[secret-scanner] " .. err, vim.log.levels.ERROR)
    return false
  end

  local cfg = config.get()

  local hooks = { "pre-commit" }
  if cfg.pre_push_hook then
    table.insert(hooks, "pre-push")
  end

  local installed = false
  for _, name in ipairs(hooks) do
    local path = dir .. "/" .. name
    local legacy = dir .. "/" .. backup_name(name)

    local has_existing = vim.fn.filereadable(path) == 1
    local is_ours = false
    if has_existing then
      local content = table.concat(vim.fn.readfile(path, "", 100), "\n")
      is_ours = content:find(MARKER, 1, true) ~= nil
    end

    if has_existing and not is_ours then
      if vim.fn.filereadable(legacy) == 0 then
        copy_file(path, legacy)
        vim.notify(
          string.format("[secret-scanner] backed up existing %s to %s", name, backup_name(name)),
          vim.log.levels.INFO
        )
      end
    end

    vim.fn.writefile(build_script(name), path)
    vim.fn.setfperm(path, "rwxr-xr-x")

    vim.notify(string.format("[secret-scanner] installed %s hook in %s", name, dir), vim.log.levels.INFO)
    installed = true
  end

  if installed then
    vim.notify(
      "[secret-scanner] hooks installed. Commits from any terminal are now scanned by gitleaks.",
      vim.log.levels.INFO
    )
  end
  return installed
end

--- Uninstall hooks. Restores a backed-up legacy hook if one exists.
--- @param repo_root? string
--- @return boolean success
function M.uninstall(repo_root)
  local root = repo_root or vim.fn.getcwd()
  local dir, err = hooks_dir(root)
  if not dir then
    vim.notify("[secret-scanner] " .. err, vim.log.levels.ERROR)
    return false
  end

  local removed = false
  for _, name in ipairs({ "pre-commit", "pre-push" }) do
    local path = dir .. "/" .. name
    local legacy = dir .. "/" .. backup_name(name)

    if vim.fn.filereadable(path) == 1 then
      local content = table.concat(vim.fn.readfile(path, "", 100), "\n")
      if content:find(MARKER, 1, true) then
        vim.fn.delete(path)
        if vim.fn.filereadable(legacy) == 1 then
          vim.fn.rename(legacy, path)
          vim.notify(string.format("[secret-scanner] restored previous %s hook", name), vim.log.levels.INFO)
        else
          vim.notify(string.format("[secret-scanner] removed %s hook", name), vim.log.levels.INFO)
        end
        removed = true
      end
    end
  end

  if not removed then
    vim.notify("[secret-scanner] no managed hooks found to remove", vim.log.levels.INFO)
  end
  return removed
end

return M
