local plugin = require("secret-scanner")

describe("secret-scanner", function()
  it("setup() does not error with default opts", function()
    assert.has_no.errors(function()
      plugin.setup()
    end)
  end)

  it("setup() merges user opts", function()
    local config = require("secret-scanner.config")
    plugin.setup({ scan_on_save = false, timeout = 5000 })
    assert.is_false(config.values.scan_on_save)
    assert.is.equal(5000, config.values.timeout)
    assert.is.equal("gitleaks", config.values.gitleaks_path)
  end)

  it("config.get() returns current config", function()
    local config = require("secret-scanner.config")
    plugin.setup()
    local cfg = config.get()
    assert.is.table(cfg)
    assert.is.equal("gitleaks", cfg.gitleaks_path)
  end)

  it("scan() does not error", function()
    assert.has_no.errors(function()
      plugin.scan()
    end)
  end)

  it("scan_staged() does not error", function()
    assert.has_no.errors(function()
      plugin.scan_staged()
    end)
  end)

  it("scan_repo() does not error and yields a qflist", function()
    assert.has_no.errors(function()
      plugin.scan_repo()
    end)
  end)
end)
